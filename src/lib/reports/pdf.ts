import "server-only";
import PDFDocument from "pdfkit";
import { EMAIL_LOGO_BASE64 } from "@/lib/email-logo";
import { formatDate } from "@/lib/time";

const MARGIN = 40;
const FOOTER_ZONE = 24; // reserved strip below the normal bottom margin, for the footer only
const PAGE_WIDTH = 841.89; // A4 landscape, points
const PAGE_HEIGHT = 595.28;
const CONTENT_RIGHT = PAGE_WIDTH - MARGIN;
const CONTENT_BOTTOM = PAGE_HEIGHT - MARGIN; // where normal content must stop

/** Branded report PDF: CAA logo, title, generated-by/timestamp, a table, and a
 *  "Confidential" footer repeated on every page (spec §5.10). */
export function createReportDocument({ title, generatedBy }: { title: string; generatedBy: string }) {
  const doc = new PDFDocument({ margins: { top: MARGIN, bottom: MARGIN, left: MARGIN, right: MARGIN }, size: "A4", layout: "landscape" });
  const logo = Buffer.from(EMAIL_LOGO_BASE64, "base64");
  const timestamp = formatDate(new Date(), { day: "numeric", month: "short", year: "numeric", hour: "numeric", minute: "2-digit" });

  // Drawing inside the bottom margin (the footer) would otherwise make pdfkit think the
  // content overflowed and auto-paginate — which re-fires "pageAdded" → footer() → another
  // overflow, forever. Zeroing the bottom margin just for this call lets it draw into that
  // reserved strip without tripping pdfkit's own pagination check.
  function footer() {
    const savedX = doc.x;
    const savedY = doc.y;
    const savedBottom = doc.page.margins.bottom;
    doc.page.margins.bottom = 0;
    doc.fontSize(8).fillColor("#6B6760").text(`Confidential — Uganda Civil Aviation Authority, Legal Department · Generated by ${generatedBy} on ${timestamp}`, MARGIN, PAGE_HEIGHT - FOOTER_ZONE + 6, {
      width: CONTENT_RIGHT - MARGIN,
      align: "center",
      lineBreak: false,
    });
    doc.page.margins.bottom = savedBottom;
    doc.x = savedX;
    doc.y = savedY;
  }

  function header() {
    doc.image(logo, MARGIN, MARGIN, { width: 42, height: 20 });
    doc.fontSize(8).fillColor("#4169E1").text("CAA LEGAL DEPARTMENT", MARGIN + 50, MARGIN + 2, { lineBreak: false });
    doc.fontSize(16).fillColor("#1F2328").text(title, MARGIN + 50, MARGIN + 13, { lineBreak: false });
    doc.moveTo(MARGIN, MARGIN + 42).lineTo(CONTENT_RIGHT, MARGIN + 42).strokeColor("#E6E3DD").stroke();
    doc.x = MARGIN;
    doc.y = MARGIN + 54;
    footer();
  }

  doc.on("pageAdded", footer);
  header();

  function ensureSpace(rowHeight: number) {
    if (doc.y + rowHeight > CONTENT_BOTTOM - FOOTER_ZONE) doc.addPage({ margins: { top: MARGIN, bottom: MARGIN, left: MARGIN, right: MARGIN }, size: "A4", layout: "landscape" });
  }

  function table(rawColumns: { label: string; width: number }[], rows: string[][]) {
    // Scale every column down proportionally if the caller's widths would run past the
    // page edge — a column simply overflowing off the right side is a silent data-loss bug,
    // not a style nitpick, so this guards every report rather than trusting each width by hand.
    const available = CONTENT_RIGHT - MARGIN;
    const total = rawColumns.reduce((a, c) => a + c.width, 0);
    const scale = total > available ? available / total : 1;
    const columns = rawColumns.map((c) => ({ ...c, width: c.width * scale }));

    const startX = MARGIN;
    let y = doc.y;
    doc.fontSize(9).fillColor("#1F2328").font("Helvetica-Bold");
    columns.forEach((c, i) => {
      const x = startX + columns.slice(0, i).reduce((a, b) => a + b.width, 0);
      doc.text(c.label, x, y, { width: c.width, lineBreak: false });
    });
    y += 14;
    doc.moveTo(startX, y).lineTo(CONTENT_RIGHT, y).strokeColor("#E6E3DD").stroke();
    y += 5;
    doc.font("Helvetica").fontSize(8.5).fillColor("#1F2328");

    for (const row of rows) {
      ensureSpace(16);
      y = doc.y;
      row.forEach((cell, i) => {
        const x = startX + columns.slice(0, i).reduce((a, b) => a + b.width, 0);
        doc.text(cell, x, y, { width: columns[i].width, height: 13, ellipsis: true });
      });
      doc.y = y + 15;
    }
  }

  return { doc, table, ensureSpace };
}
