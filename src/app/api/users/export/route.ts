import { NextResponse, type NextRequest } from "next/server";
import ExcelJS from "exceljs";
import PDFDocument from "pdfkit";
import { db } from "@/lib/db";
import { getCurrentUser } from "@/lib/session";
import { writeAudit } from "@/lib/audit";
import { formatDate } from "@/lib/time";
import { buildUserWhere, parseUserFilters } from "@/app/(app)/users/filters";

const COLUMNS = [
  { header: "Name", key: "name", width: 26 },
  { header: "Email", key: "email", width: 30 },
  { header: "Phone", key: "phone", width: 18 },
  { header: "Title", key: "title", width: 22 },
  { header: "Department", key: "department", width: 16 },
  { header: "Practising cert. no.", key: "practisingCertNo", width: 20 },
  { header: "Cert. expiry", key: "certExpiry", width: 14 },
  { header: "Role", key: "role", width: 10 },
  { header: "Status", key: "status", width: 14 },
  { header: "Last signed in", key: "lastLoginAt", width: 16 },
];

function statusOf(u: { isActive: boolean; accounts: unknown[] }) {
  if (!u.isActive) return "Deactivated";
  return u.accounts.length > 0 ? "Active" : "Invited";
}

export async function GET(request: NextRequest) {
  const me = await getCurrentUser();
  if (!me || me.role !== "ADMIN") return new NextResponse("Forbidden", { status: 403 });

  const url = new URL(request.url);
  const format = url.searchParams.get("format") === "pdf" ? "pdf" : "xlsx";
  const filters = parseUserFilters(Object.fromEntries(url.searchParams));

  const users = await db.user.findMany({
    where: buildUserWhere(filters),
    orderBy: [{ isActive: "desc" }, { name: "asc" }],
    include: { accounts: { where: { providerId: "credential" }, select: { id: true } } },
  });

  await writeAudit({ userId: me.id, action: "user.export", entity: "User", after: { format, count: users.length } });

  const rows = users.map((u) => ({
    name: u.name,
    email: u.email,
    phone: u.phone ?? "",
    title: u.title ?? "",
    department: u.department ?? "",
    practisingCertNo: u.practisingCertNo ?? "",
    certExpiry: u.certExpiry ? formatDate(u.certExpiry) : "",
    role: u.role === "ADMIN" ? "Admin" : "Lawyer",
    status: statusOf(u),
    lastLoginAt: u.lastLoginAt ? formatDate(u.lastLoginAt) : "Never",
  }));

  const timestamp = formatDate(new Date(), { day: "2-digit", month: "2-digit", year: "numeric" });

  if (format === "xlsx") {
    const workbook = new ExcelJS.Workbook();
    const sheet = workbook.addWorksheet("Users");
    sheet.columns = COLUMNS;
    sheet.getRow(1).font = { bold: true };
    sheet.addRows(rows);
    const buffer = await workbook.xlsx.writeBuffer();
    return new NextResponse(new Uint8Array(buffer), {
      headers: {
        "Content-Type": "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
        "Content-Disposition": `attachment; filename="caa-legal-users-${Date.now()}.xlsx"`,
      },
    });
  }

  // PDF — a plain, functional roster. The branded version (logo, richer layout) is Phase 11 Reports.
  const doc = new PDFDocument({ margin: 40, size: "A4", layout: "landscape" });
  const chunks: Buffer[] = [];
  doc.on("data", (c) => chunks.push(c));
  const done = new Promise<Buffer>((resolve) => doc.on("end", () => resolve(Buffer.concat(chunks))));

  doc.fontSize(8).fillColor("#2F5E9E").text("CAA LEGAL", { continued: false });
  doc.fontSize(16).fillColor("#1F2328").text("Case & Matter Management — Lawyer Roster", { continued: false });
  doc.fontSize(9).fillColor("#6B6760").text(`Generated by ${me.name} on ${timestamp} · Confidential`);
  doc.moveDown(1);

  const colWidths = [110, 150, 90, 110, 70, 90, 70, 50, 70];
  const headers = ["Name", "Email", "Phone", "Title", "Dept.", "Cert. no.", "Cert. expiry", "Role", "Status"];
  let y = doc.y;
  doc.fontSize(9).fillColor("#1F2328");
  headers.forEach((h, i) => doc.text(h, 40 + colWidths.slice(0, i).reduce((a, b) => a + b, 0), y, { width: colWidths[i], continued: false }));
  y += 16;
  doc.moveTo(40, y).lineTo(760, y).strokeColor("#E6E3DD").stroke();
  y += 6;

  doc.fontSize(8.5).fillColor("#1F2328");
  for (const r of rows) {
    if (y > 520) {
      doc.addPage();
      y = 40;
    }
    const values = [r.name, r.email, r.phone, r.title, r.department, r.practisingCertNo, r.certExpiry, r.role, r.status];
    values.forEach((v, i) => doc.text(v, 40 + colWidths.slice(0, i).reduce((a, b) => a + b, 0), y, { width: colWidths[i] }));
    y += 16;
  }

  doc.end();
  const buffer = await done;
  return new NextResponse(new Uint8Array(buffer), {
    headers: {
      "Content-Type": "application/pdf",
      "Content-Disposition": `attachment; filename="caa-legal-users-${Date.now()}.pdf"`,
    },
  });
}
